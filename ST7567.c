//=============写命令=================
// 使用硬件SPI发送LCD命令字节
void LcdWriteCmd(unsigned char cmd)
{
    SD_CS = 1;              // 确保SD卡未选中，避免SPI总线冲突
    LCD_CS = 0;             // 片选有效
    LCD_A0 = 0;             // 命令模式
    SPI_WriteByte(cmd);     // 硬件SPI发送一个字节
    LCD_CS = 1;             // 片选无效
    delay_us(1);
}

// 写数据函数
// 使用硬件SPI发送LCD数据字节
void LcdWriteData(unsigned char dat)
{
    SD_CS = 1;              // 确保SD卡未选中，避免SPI总线冲突
    LCD_CS = 0;             // 片选有效
    LCD_A0 = 1;             // 数据模式
    SPI_WriteByte(dat);     // 硬件SPI发送一个字节
    LCD_A0 = 0;
    LCD_CS = 1;             // 片选无效
    delay_us(1);
}

//===========LCD_清12864屏=============
void LcdCLS(void)
{
    uint16_t i;uint8_t page=0;

	
    for(; page<8; page++)
    {
        LcdWriteCmd(0xB0 | page);
        LcdWriteCmd(0x10);
        LcdWriteCmd(0x00);

        LCD_A0 = 1;

        LCD_CS = 0;

        for(i=0; i<128; i++)
        {
            LcdWriteData(0x00);
        }

        LCD_CS = 1;
    }
		
}

//==================液晶初始化=============
void LcdInit(void)
{
    delay_us(1);
    LCD_CS = 0;
    LCD_RST = 0;    delay_us(1);
    LCD_RST = 1;
    delay_us(1);

    LcdWriteCmd(0xA2);
    LcdWriteCmd(0xA0);
    LcdWriteCmd(0x80);
    delay_us(1);
    LcdWriteCmd(0x27);
    LcdWriteCmd(0x81);
    LcdWriteCmd(0x06);      // ← 改大对比度，原来0x04
    LcdWriteCmd(0xc8);
    LcdWriteCmd(0xa6);
    delay_us(1);
    LcdWriteCmd(0x2f);
    delay_us(1);
    LcdWriteCmd(0xF8);
    LcdWriteCmd(0x00);
    delay_us(1);
    LcdWriteCmd(0xAF);      // 显示开
    delay_us(1);
    LcdWriteCmd(0xa4);      // 正常显示
    LcdCLS();
    delay_us(1);
    LCD_CS = 1;
    delay_us(1);
}

