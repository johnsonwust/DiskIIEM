/*******************************************************************************
 * 将ASCII字符转换为s0数组索引（0表示空格）
 * 参数：ch - 要显示的字符
 * 返回值：s0数组下标
 *******************************************************************************/
unsigned char CharToIndex(unsigned char ch)
{
    if (ch == ' ')      return 0;                // 空格
    if (ch >= '!' && ch <= '~') return (ch - '!' + 1); // '!' -> 1, '~' -> 94
    return 0;           // 其他不支持字符，显示空格
}

/*******************************************************************************
 * 功能：在LCD12864上显示字符串，支持自动换行，最多显示64个字符
 * 参数：startX - 起始列（0~15）
 *       startY - 起始行（0~3）
 *       *p     - 待显示字符串指针
 *******************************************************************************/
void LcdWriteStr(unsigned char col, unsigned char row, unsigned char *p)
{
    unsigned char idx = 0;            // 字符串索引
    unsigned char cnt = 0;            // 已显示字符计数
    unsigned char ch;
unsigned char s0_idx;
		row<<=1;
    while (p[idx] != '\0' && cnt < 64)
    {
        ch = p[idx];
        s0_idx = CharToIndex(ch);  // 转换为字模索引

        // 调用单个字符显示函数（第三个参数为字模索引）
        LcdWriteLetter(row, col, s0_idx, 0);

        // 移动到下一个字符位置
        col++;
        if (col >= 16)          // 每行16个字符
        {
            col = 0;
            row++;
            if (row >= 4) break; // 第4行之后停止显示
        }
        idx++;
        cnt++;
    }
}
